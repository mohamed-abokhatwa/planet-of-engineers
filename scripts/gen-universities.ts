// Builds supabase/migrations/0005_universities.sql from the open university list (see data/universities/README.md).
//   npx tsx scripts/gen-universities.ts
import { readFileSync, writeFileSync } from 'fs';

interface Uni { name: string; alpha_two_code: string; domains: string[]; web_pages: string[] }

/** Institutions that clearly teach no engineering. Kept small on purpose: when in doubt, a university stays in. */
export const NON_ENGINEERING =
  /\b(medical|medicine|nursing|dental|dentistry|pharmacy|pharmaceutical|health sciences?|allied health|veterinary|music|conservatory|conservatoire|film|theolog\w*|seminary|bible|divinity|rabbinical|law school|school of law|culinary|cosmetology|beauty|police|security college|dance|theatre|theater|fashion|hotel|tourism|hospitality|osteopath\w*|chiropractic|midwifery)\b/i;

export function cleanName(n: string) {
  return n.replace(/\s+/g, ' ').trim();
}

export function buildList(raw: Uni[]) {
  const seen = new Set<string>();
  const out: { name: string; country: string; domains: string[]; web: string | null }[] = [];
  for (const u of raw) {
    const name = cleanName(u.name);
    const country = (u.alpha_two_code ?? '').toUpperCase();
    if (!/^[A-Z]{2}$/.test(country) || name.length < 3 || name.length > 160) continue;
    if (NON_ENGINEERING.test(name)) continue;
    const key = `${country}|${name.toLowerCase()}`;
    if (seen.has(key)) continue;
    seen.add(key);
    const web = (u.web_pages ?? []).find((w) => /^https?:\/\//i.test(w)) ?? null;
    out.push({ name, country, domains: (u.domains ?? []).filter((d) => /^[a-z0-9.-]+$/i.test(d)).map((d) => d.toLowerCase()), web });
  }
  return out.sort((a, b) => a.country.localeCompare(b.country) || a.name.localeCompare(b.name));
}

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;

if (process.argv[1]?.endsWith('gen-universities.ts')) {
  const raw: Uni[] = JSON.parse(readFileSync('data/universities/world_universities_and_domains.json', 'utf8'));
  const list = buildList(raw);
  const lines = [
    '-- Universities. GENERATED by scripts/gen-universities.ts from the open Hipo list (MIT licence). Do not edit by hand.',
    `-- ${list.length} universities in ${new Set(list.map((u) => u.country)).size} countries. Safe to run again: existing names are kept.`,
  ];
  for (let i = 0; i < list.length; i += 500) {
    const rows = list.slice(i, i + 500).map((u) => `  (${q(u.name)}, ${q(u.country)}, ${u.domains.length ? `array[${u.domains.map(q).join(', ')}]` : `'{}'::text[]`}, ${u.web ? q(u.web) : 'null'})`);
    lines.push('insert into public.universities (name, country, domains, web) values', rows.join(',\n'), 'on conflict (country, lower(name)) do nothing;');
  }
  writeFileSync('supabase/migrations/0005_universities.sql', lines.join('\n') + '\n');
  console.log(`${list.length} universities, ${new Set(list.map((u) => u.country)).size} countries, ${raw.length - list.length} left out`);
}
