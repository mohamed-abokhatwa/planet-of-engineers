/** Reputation levels, like site ranks. */
export const LEVELS: { min: number; en: string; ar: string }[] = [
  { min: 0, en: 'Trainee', ar: 'متدرب' },
  { min: 50, en: 'Site Engineer', ar: 'مهندس موقع' },
  { min: 200, en: 'Project Engineer', ar: 'مهندس مشروع' },
  { min: 500, en: 'Senior Engineer', ar: 'مهندس أول' },
  { min: 1500, en: 'Chief Engineer', ar: 'كبير المهندسين' },
  { min: 5000, en: 'Legend', ar: 'أسطورة' },
];

export function levelFor(rep: number) {
  let i = 0;
  for (let k = 0; k < LEVELS.length; k++) if (rep >= LEVELS[k].min) i = k;
  const next = LEVELS[i + 1];
  return { index: i, level: LEVELS[i], next, progress: next ? (rep - LEVELS[i].min) / (next.min - LEVELS[i].min) : 1 };
}

export function format(template: string, vars: Record<string, string | number>) {
  return template.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
}
